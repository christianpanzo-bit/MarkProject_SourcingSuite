// Generate complete list covering ALL countries in COUNTRIES_DATA
export function getCompleteMinimumWageData(allCountries: { code: string; name: string; flag: string; region: any }[]): MinimumWageEntry[] {
  const result: MinimumWageEntry[] = [];
  const processedCodes = new Set<string>();

  // 1. Add explicitly configured rich entries first
  for (const entry of MINIMUM_WAGE_DATA) {
    result.push(entry);
    processedCodes.add(entry.countryCode);
  }

  // 2. Add dynamic entries for any country in COUNTRIES_DATA not yet in explicit list
  for (const country of allCountries) {
    if (!processedCodes.has(country.code)) {
      const curr = CURRENCY_DEFAULTS[country.code] || {
        code: 'USD',
        name: 'US Dollar / Local Currency',
        symbol: '$'
      };

      result.push({
        countryCode: country.code,
        countryName: country.name,
        flag: country.flag,
        region: country.region,
        currencyCode: curr.code,
        currencyName: curr.name,
        currencySymbol: curr.symbol,
        hourlyLocal: 0,
        hourlyUsd: 0,
        hourlyEur: 0,
        effectiveYear: '2026',
        hasStatutoryMinimum: false,
        notes: `No statutory minimum wage law established; wages determined by individual employment contracts or collective agreements.`
      });

      processedCodes.add(country.code);
    }
  }

  return result;
}

